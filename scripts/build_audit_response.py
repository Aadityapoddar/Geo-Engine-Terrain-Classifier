def items_table():
    rows = ["| Item | Issue | Status | What was done |",
            "| --- | --- | --- | --- |"]
    for number, issue, status, action in AUDIT_ITEMS:
        rows.append(f"| {number} | {issue} | **{status}** | {action} |")
    return "\n".join(rows)


def load(name, required=True):
    path = ASSETS / name
    if not path.exists():
        if required:
            raise SystemExit(f"missing {path}")
        return None
    return json.loads(path.read_text())


def pct(value, digits=2):
    return "n/a" if value is None else f"{value * 100:.{digits}f}%"


def ci(interval, digits=2):
    if not interval:
        return "n/a"
    low, high = interval
    return f"[{low * 100:.{digits}f}, {high * 100:.{digits}f}]"


def classifier_table(uncertainty, season, split):
    payload = uncertainty["seasons"][season][split]
    rows = ["| Model | OA | 95% CI (district block) | Kappa | Macro F1 |",
            "| --- | --- | --- | --- | --- |"]
    ordered = sorted(
        (key for key in payload["pooled"] if key in MODEL_LABEL),
        key=lambda key: -payload["pooled"][key]["overall_accuracy"],
    )
    for key in ordered:
        value = payload["pooled"][key]
        rows.append(
            f"| {MODEL_LABEL[key]} | {pct(value['overall_accuracy'])} | "
            f"{ci(value['overall_accuracy_ci95'])} | {value['kappa']:.3f} | "
            f"{value['macro_f1']:.3f} |")
    return "\n".join(rows)


def paired_table(uncertainty, season):
    payload = uncertainty["seasons"][season]
    best = payload["selected_on_development"]
    rows = ["| Comparison | Mean per-district OA difference | 95% CI | "
            "Districts won/lost/tied | Wilcoxon p |",
            "| --- | --- | --- | --- | --- |"]
    for comparison in payload["test"]["paired_comparisons"]:
        if best not in (comparison["left"], comparison["right"]):
            continue
        sign = 1 if comparison["left"] == best else -1
        other = comparison["right"] if sign == 1 else comparison["left"]
        low, high = sorted(value * sign for value in comparison["ci95"])
        won = (comparison["districts_left_better"] if sign == 1
               else comparison["districts_right_better"])
        lost = (comparison["districts_right_better"] if sign == 1
                else comparison["districts_left_better"])
        rows.append(
            f"| {MODEL_LABEL[best]} - {MODEL_LABEL[other]} | "
            f"{comparison['mean_district_oa_difference'] * sign * 100:+.2f} pp | "
            f"[{low * 100:+.2f}, {high * 100:+.2f}] | "
            f"{won}/{lost}/{comparison['districts_tied']} | "
            f"{comparison['wilcoxon_p']:.2e} |")
    return "\n".join(rows)


def stack_table(uncertainty, season):
    payload = uncertainty["seasons"][season]
    rows = ["| Feature stack | Development OA | Test OA | Test 95% CI |",
            "| --- | --- | --- | --- |"]
    for key, label in STACK_LABEL.items():
        development = payload["development"]["pooled"].get(key)
        test = payload["test"]["pooled"].get(key)
        if not development or not test:
            continue
        rows.append(
            f"| {label} | {pct(development['overall_accuracy'])} | "
            f"{pct(test['overall_accuracy'])} | "
            f"{ci(test['overall_accuracy_ci95'])} |")
    return "\n".join(rows)


def area_table(area, season):
    payload = area["seasons"][season]["test"]
    rows = ["| Class | User's accuracy | Producer's accuracy | "
            "Area-adjusted area (km2) | 95% CI (km2) |",
            "| --- | --- | --- | --- | --- |"]
    for label, value in payload["per_class"].items():
        rows.append(
            f"| {label} | {pct(value['users_accuracy'], 1)} | "
            f"{pct(value['producers_accuracy'], 1)} | "
            f"{value['mapped_area_km2']:,.0f} | "
            f"+/- {value['mapped_area_ci95_km2']:,.0f} |")
    return "\n".join(rows)


def transfer_table(uncertainty, season):
    payload = uncertainty["seasons"][season]
    rows = ["| Class | Recall slope per 100 km | p | Mean recall |",
            "| --- | --- | --- | --- |"]
    for label, value in payload["class_transfer"].items():
        rows.append(
            f"| {label} | {value['slope_recall_per_100km'] * 100:+.2f} pp | "
            f"{value['p_value']:.3f} | {pct(value['mean_recall'], 1)} |")
    return "\n".join(rows)


def protocol_table(splits):
    if not splits:
        return "_Not yet measured._"
    rows = ["| Protocol | Season | n | Overall accuracy across the five models |",
            "| --- | --- | --- | --- |"]
    label = {"random": "Random held-out split, Jabalpur points",
             "spatially_blocked": "Spatially blocked split, same points"}
    for season, payload in splits["seasons"].items():
        for name, entry in payload["protocols"].items():
            low, high = entry["overall_accuracy_range"]
            rows.append(f"| {label[name]} | {season} | "
                        f"{entry['sample_count']:,} | "
                        f"{low * 100:.1f}-{high * 100:.1f}% |")
    return "\n".join(rows)


def depth_table(depth):
    rows = ["| Season | Window | Days | Mean S-2 scenes | Mean S-1 scenes | "
            "Districts with no in-window S-1 |",
            "| --- | --- | --- | --- | --- | --- |"]
    for season, window in depth["seasons"].items():
        records = [record for record in depth["records"].values()
                   if record["season"] == season]
        count = len(records)
        rows.append(
            f"| {season} | {window['start']} to {window['end']} | 59 | "
            f"{sum(r['s2_scenes'] for r in records) / count:.1f} | "
            f"{sum(r['s1_scenes'] for r in records) / count:.1f} | "
            f"{sum(r['s1_missing'] for r in records)} |")
    return "\n".join(rows)


