def family_table(families):
    """Cumulative feature families, with the open-land recall the paper cites."""
    if not families or "scores" not in families:
        return "_Not yet measured._"
    order = ["g10_baseline", "g15_bareness", "g21_texture", "g27_sar"]
    label = {"g10_baseline": "Optical + core indices (10)",
             "g15_bareness": "+ bareness/built indices (15)",
             "g21_texture": "+ optical GLCM texture (21)",
             "g27_sar": "+ Sentinel-1 and SAR texture (27)"}
    rows = ["| Season | Model | Feature set | OA | Open Land recall | "
            "Built Area precision |", "| --- | --- | --- | --- | --- | --- |"]
    for season, scores in families["scores"].items():
        for model in ("rf", "gtb"):
            for stack in order:
                key = f"{model}:{stack}"
                if key not in scores:
                    continue
                value = scores[key]
                recall = value.get("per_class_recall", {}).get("Open Land")
                precision = value.get("per_class_precision", {}).get("Built Area")
                rows.append(
                    f"| {season} | {model.upper()} | {label[stack]} | "
                    f"{pct(value['overall_accuracy'])} | {pct(recall, 1)} | "
                    f"{pct(precision, 1)} |")
    return "\n".join(rows)


def band_selection_section(per_band, comparison):
    """The band study, re-run: what each band is worth and which stack wins."""
    if not per_band or not comparison:
        return "_Not yet measured._"
    lines = []
    ablation = per_band.get("ablation", {})
    for season, payload in ablation.items():
        droppable = payload["droppable_bands"]
        rows = sorted(payload["bands"], key=lambda row: row["delta_points"])
        costly = ", ".join(f"`{row['band']}` ({row['delta_points']:+.2f})"
                           for row in rows[:4])
        lines += [
            f"- **{season}**, 27-band baseline "
            f"{payload['baseline_overall_accuracy'] * 100:.2f}%. Least "
            f"affordable to lose: {costly}. Removable without measurable loss "
            f"({len(droppable)}): "
            + (", ".join(f"`{band}`" for band in droppable) or "none"),
        ]
    both = comparison.get("droppable_in_both")
    lines.append(
        f"- Removable in **both** seasons: "
        + (", ".join(f"`{band}`" for band in both) if both else
           "**none** — the two seasons never agree that a band is spare."))

    from scripts.adopt_band_stack import select_stack
    chosen, mean_scores = select_stack(comparison)
    rows = ["", "| Stack | Bands | Winter dev / test | Summer dev / test | "
            "Mean dev |", "| --- | --- | --- | --- | --- |"]
    for name in sorted(mean_scores, key=lambda n: -mean_scores[n]):
        cells = []
        for season in ("winter", "summer"):
            payload = comparison["seasons"][season]
            cells.append(
                f"{payload['development'][name]['overall_accuracy'] * 100:.2f} / "
                f"{payload['test'][name]['overall_accuracy'] * 100:.2f}")
        mark = " **<- selected**" if name == chosen else ""
        rows.append(f"| `{name}` | {len(comparison['stacks'][name])} | "
                    f"{cells[0]} | {cells[1]} | "
                    f"{mean_scores[name] * 100:.2f}{mark} |")
    rows += [
        "",
        "Selection is by mean development accuracy over the two reported "
        "seasons. A single-season rule would have been arbitrary here, because "
        "the seasons disagree: winter development prefers `"
        + comparison["seasons"]["winter"]["selected_on_development"]
        + "` and summer prefers `"
        + comparison["seasons"]["summer"]["selected_on_development"]
        + "`. For full disclosure, the test column was already visible when "
        "that rule was settled; it is reported here so a reader can judge the "
        "choice rather than take it on trust.",
    ]
    return "\n".join(lines + rows)


def tuning_table(tuning):
    if not tuning or "best_per_model" not in tuning:
        return "_Not yet measured._"
    rows = ["| Model | Best development OA | Selected settings | Shipped "
            "settings |", "| --- | --- | --- | --- |"]
    shipped = {
        "rf": "trees 200, bag 0.3, maxNodes 10",
        "gtb": "trees 100, shrinkage 0.1, maxNodes 10",
        "svm": "RBF, gamma 1.0, cost 100",
        "cart": "maxNodes 20",
        "knn": "k 5",
    }
    for season, best in tuning["best_per_model"].items():
        rows.append(f"| _{season}_ | | | |")
        for model, value in sorted(
                best.items(), key=lambda item: -item[1]["overall_accuracy"]):
            rows.append(
                f"| {model.upper()} | {pct(value['overall_accuracy'])} | "
                f"{value['config'].split(':', 1)[1]} | {shipped[model]} |")
    return "\n".join(rows)


