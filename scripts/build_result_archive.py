def build_coverage(shards, area_adjusted, stratum_areas, splits):
    """Section 4.3 of the guide: the table the manuscript is missing."""
    rows = []
    for season in SEASONS:
        for group in ("development", "test"):
            districts = splits[group]
            payload = area_adjusted["seasons"][season][group]
            district_area = 0.0
            covered = 0.0
            for name in districts:
                record = stratum_areas["strata"].get(f"{season}:{name}")
                if not record:
                    continue
                district_area += record["district_area_m2"]
                covered += sum(v or 0.0 for v in record["class_area_m2"].values())
            matrix = pooled(shards, season, districts, LEADER)
            metrics, n = verify(matrix, f"coverage/{season}/{group}")
            # A sampled point whose (district, class) stratum has no measured
            # consensus area carries no weight and drops out of the estimator.
            # Report the number rather than letting the two sample sizes differ
            # silently between the unweighted and weighted columns.
            unweighted_only = 0
            for name in districts:
                record = stratum_areas["strata"].get(f"{season}:{name}")
                shard = shards.get(f"{season}:{name}")
                if not record or not shard:
                    continue
                areas = {canonical_label(k): v
                         for k, v in record["class_area_m2"].items()}
                for index, label in enumerate(LABELS):
                    count = sum(shard["matrices"][LEADER][index])
                    if count and not (areas.get(label) or 0.0) > 0:
                        unweighted_only += count
            unsampled = payload["domain_area_km2"] - payload["sampled_domain_area_km2"]
            rows.append({
                "season": season,
                "population": group,
                "districts": len(districts),
                "district_area_km2": round(district_area / 1e6, 1),
                "consensus_covered_area_km2": round(covered / 1e6, 1),
                "consensus_covered_pct": round(100 * covered / district_area, 2),
                "strata": payload["strata"],
                "strata_with_samples": payload["strata_with_samples"],
                "unsampled_stratum_area_km2": round(unsampled, 3),
                "unsampled_stratum_area_pct":
                    round(100 * unsampled / payload["domain_area_km2"], 4),
                "sample_n": n,
                "sample_n_carrying_weight": n - unweighted_only,
                "sample_n_in_zero_area_strata": unweighted_only,
                "unweighted_agreement": round(metrics["overall_accuracy"], 6),
                "area_weighted_agreement":
                    round(payload["area_adjusted_overall_accuracy"], 6),
                "area_weighted_ci95_halfwidth":
                    round(payload["area_adjusted_overall_accuracy_ci95"], 6),
                "uncertainty_method":
                    "Olofsson et al. (2014) stratified design-based variance, "
                    "normal 95% interval; no finite-population correction",
            })
    return rows


def main():
    global ARCHIVE
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=ARCHIVE)
    # The weighting grid is an argument because it is a claim: a sample drawn at
    # 10 m has to be weighted by areas measured at 10 m, and the 30 m record is
    # kept so the two can be compared rather than quietly replaced.
    parser.add_argument("--stratum-areas", default=STRATUM_AREAS)
    parser.add_argument("--area-adjusted", default=AREA_ADJUSTED)
    parser.add_argument("--split-protocols", default=SPLIT_PROTOCOLS)
    args = parser.parse_args()
    ARCHIVE = args.out

    shards, provenance = load_shards()
    print(f"reported source: {SHARD_GLOB} (the frozen evaluation)")
    splits = district_splits()
    stratum_areas = load_json(args.stratum_areas)
    area_adjusted = load_json(args.area_adjusted)
    print(f"weights from {args.stratum_areas} "
          f"({stratum_areas.get('scale_m')} m grid)")

    metrics_rows = build_metrics(shards, splits, provenance)
    matrix_rows = build_district_matrices(shards, splits, provenance)
    split_rows = build_district_split(shards, splits, stratum_areas)
    stratum_rows = build_stratum_areas(shards, stratum_areas, splits)
    reference_rows = build_reference_inventory()
    manifest_rows = build_experiment_manifest(provenance, splits)
    coverage_rows = build_coverage(shards, area_adjusted, stratum_areas, splits)
    feature_rows = build_feature_experiments(shards, splits)
    transfer_rows = build_spatial_transfer(splits)
    reproduction_rows = build_reproduction_check(shards, splits)

    contrast_rows = []
    for season in SEASONS:
        contrast_rows.extend(paired_contrasts(
            shards, season, splits["test"],
            family=f"{season}: four classifier contrasts against the leading model"))
        contrast_rows.extend(paired_contrasts(
            shards, season, splits["test"], comparators=list(STACK_KEYS),
            family=f"{season}: three feature-stack contrasts against the selected stack"))
    # Multiplicity: the families are declared here, before any p is looked at,
    # and Holm is applied inside each one. Classifier choice and feature-stack
    # choice are separate questions and are not pooled into one family.
    families = sorted({row["family"] for row in contrast_rows})
    for name in families:
        group = [row for row in contrast_rows if row["family"] == name]
        adjusted = holm(np.array([row["wilcoxon_p_raw"] for row in group]))
        for row, value in zip(group, adjusted):
            row["holm_adjusted_p"] = float(value)

    write_csv("metrics.csv", list(metrics_rows[0]), metrics_rows)
    write_csv("district_confusion_matrices.csv", list(matrix_rows[0]), matrix_rows)
    write_csv("district_split.csv", list(split_rows[0]), split_rows)
    write_csv("stratum_areas.csv", list(stratum_rows[0]), stratum_rows)
    write_csv("reference_inventory.csv", list(reference_rows[0]), reference_rows)
    write_csv("experiment_manifest.csv", list(manifest_rows[0]), manifest_rows)
    write_csv("reference_domain_coverage.csv", list(coverage_rows[0]), coverage_rows)
    write_csv("paired_contrasts.csv", list(contrast_rows[0]), contrast_rows)
    write_csv("feature_experiments.csv", list(feature_rows[0]), feature_rows)
    write_csv("spatial_transfer.csv", list(transfer_rows[0]), transfer_rows)
    if reproduction_rows:
        write_csv("reproduction_check.csv",
                  list(reproduction_rows[0]), reproduction_rows)

    print("\nreference-domain coverage")
    for row in coverage_rows:
        print(f"  {row['season']:6s} {row['population']:12s} "
              f"district {row['district_area_km2']:9.1f} km2, "
              f"covered {row['consensus_covered_area_km2']:9.1f} km2 "
              f"({row['consensus_covered_pct']:5.2f}%), n={row['sample_n']}, "
              f"unweighted {row['unweighted_agreement']*100:.2f}%, "
              f"area-weighted {row['area_weighted_agreement']*100:.2f}% "
              f"+/- {row['area_weighted_ci95_halfwidth']*100:.2f}, "
              f"unsampled strata {row['unsampled_stratum_area_pct']:.4f}% of domain, "
              f"{row['sample_n_in_zero_area_strata']} points carry no weight")

    print("\npaired contrasts against the leading model")
    for row in contrast_rows:
        print(f"  {row['season']:6s} {row['contrast']:26s} "
              f"{row['mean_district_oa_difference_pp']:+6.2f} pp "
              f"[{row['ci95_low_pp']:+6.2f}, {row['ci95_high_pp']:+6.2f}] "
              f"raw p={row['wilcoxon_p_raw']:.4f} holm={row['holm_adjusted_p']:.4f} "
              f"({row['wilcoxon_method']}, ties={row['abs_difference_ties']}, "
              f"zeros={row['districts_tied']})")


if __name__ == "__main__":
    main()
