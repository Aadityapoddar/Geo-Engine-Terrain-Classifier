"""Freeze every reported number into one auditable archive of flat files.

The correction guide's first demand is that the manuscript stop quoting numbers
that no single stored record produces. Figures and tables in this project were
generated by six different scripts reading four generations of JSON, and the
only way a reader could check one against another was to trust that two authors
had copied the same value. This script removes that trust step: it reads the
stored evaluation shards, recomputes every metric from the confusion matrices
themselves, asserts the arithmetic identities the guide lists, and writes the
result as CSV that the paper's tables are then generated from.

    n            = sum(C)
    correct      = trace(C)
    OA           = trace(C) / n
    recall_i     = C_ii / row_i
    precision_i  = C_ii / col_i
    F1_i         = 2 C_ii / (row_i + col_i)

Nothing here contacts Earth Engine. Everything is derived from records already
in doc/assets, so the archive can be rebuilt and diffed on any machine.

Two records, and which is which matters.

The *reported* record is the stored per-district confusion matrices from the
frozen evaluation. Those are what the manuscript quotes, and they stay that
way: re-running an evaluation after its results have been read and then
reporting the re-run is how a held-out set stops being held out, whatever the
intention. The guide is explicit that old versions are preserved rather than
relabelled, so they are.

The *auditable* record is predictions.csv, one row per sampled reference pixel
with its coordinates, its stratum, its reference label and one predicted label
per model, written by scripts/export_predictions_table.py. It lets a reader
re-stratify the sample, recompute a weight, or look at a single pixel, none of
which a confusion matrix allows.

The two do not agree to the last pixel, and reproduction_check.csv says by how
much. Neither the Sentinel archives nor Earth Engine's server-side classifiers
are bit-stable across months, so a re-run moves a few points per district. That
number is published rather than hidden, and it is a property of the platform
worth knowing: it bounds how precisely any Earth Engine result of this kind can
be reproduced at all.
"""

