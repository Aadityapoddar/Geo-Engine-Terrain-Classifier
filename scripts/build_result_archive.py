# ── loading ────────────────────────────────────────────────────────────────
def load_shards():
    shards, provenance = {}, {}
    for path in sorted(ASSETS.glob(SHARD_GLOB)):
        payload = json.loads(path.read_text())
        for key, shard in payload["shards"].items():
            if key in shards:
                raise ValueError(f"duplicate shard {key} in {path.name}")
            shards[key] = shard
            provenance[key] = {
                "file": path.name,
                "schema": payload["training_schema_version"],
                "updated_at": payload.get("updated_at"),
            }
    if not shards:
        raise SystemExit(f"no shards matched {SHARD_GLOB}")
    return shards, provenance


def load_json(name):
    return json.loads((ASSETS / name).read_text())


def shards_from_predictions(path):
    """Fold the row-level table back into the same per-district shard shape.

    Everything downstream already speaks confusion matrices, so rather than
    teach it a second vocabulary the rows are aggregated here, once, into
    exactly the structure load_shards returns. The rows stay the record; this
    is just the projection of them the metrics are computed through.
    """
    index = {label: position for position, label in enumerate(LABELS)}
    shards, provenance = {}, {}
    with path.open(newline="") as handle:
        for row in csv.DictReader(handle):
            key = f"{row['season']}:{row['district']}"
            shard = shards.setdefault(key, {
                "season": row["season"], "district": row["district"],
                "sample_count": 0, "matrices": {}})
            shard["sample_count"] += 1
            reference = index[row["reference_label"]]
            for column, value in row.items():
                if not column.startswith("predicted_"):
                    continue
                model = column[len("predicted_"):]
                matrix = shard["matrices"].setdefault(
                    model, [[0] * len(LABELS) for _ in LABELS])
                matrix[reference][index[value]] += 1
            provenance[key] = {"file": path.name, "schema": "predictions.csv",
                               "updated_at": None}
    if not shards:
        raise SystemExit(f"{path} has no rows")
    return shards, provenance


# ── arithmetic the guide asks to be asserted rather than assumed ───────────
def verify(matrix, label):
    """Recompute every identity in section 2 of the correction guide."""
    array = np.asarray(matrix, dtype=float)
    n = array.sum()
    if n == 0:
        raise ValueError(f"{label}: empty matrix")
    rows, columns = array.sum(axis=1), array.sum(axis=0)
    diagonal = np.diag(array)
    metrics = metrics_from_matrix([[int(v) for v in row] for row in matrix], LABELS)

    assert math.isclose(metrics["overall_accuracy"], diagonal.sum() / n, abs_tol=1e-12), label
    for index, name in enumerate(LABELS):
        # A None is the deliberate signal that a marginal was zero, so the
        # metric is undefined rather than perfect. Check that reading too.
        recall = diagonal[index] / rows[index] if rows[index] else None
        precision = diagonal[index] / columns[index] if columns[index] else None
        denominator = rows[index] + columns[index]
        f1 = (2 * diagonal[index] / denominator) if denominator else None
        stored = metrics["per_class"][name]
        for key, value in (("recall", recall), ("precision", precision), ("f1", f1)):
            if value is None or stored[key] is None:
                assert value is None and stored[key] is None, f"{label}: {name}.{key}"
                continue
            assert math.isclose(stored[key], value, abs_tol=1e-12), \
                f"{label}: {name}.{key} {stored[key]} != {value}"

    # Kappa from the same matrix and the same marginals.
    expected = float((rows * columns).sum()) / (n * n)
    observed = diagonal.sum() / n
    kappa = (observed - expected) / (1 - expected) if expected != 1 else 0.0
    assert math.isclose(metrics["kappa"], kappa, abs_tol=1e-12), label
    return metrics, int(n)


def pooled(shards, season, districts, key):
    total = np.zeros((len(LABELS), len(LABELS)), dtype=int)
    for district in districts:
        shard = shards.get(f"{season}:{district}")
        if shard and key in shard["matrices"]:
            total += np.asarray(shard["matrices"][key], dtype=int)
    return total.tolist()


# ── paired classifier contrasts, with multiplicity handled explicitly ──────
def oa(matrix):
    array = np.asarray(matrix, dtype=float)
    total = array.sum()
    return float(np.trace(array) / total) if total else float("nan")


def holm(p_values):
    """Holm-Bonferroni step-down adjusted p-values, monotonised."""
    order = np.argsort(p_values)
    adjusted = np.empty(len(p_values))
    running = 0.0
    for rank, index in enumerate(order):
        running = max(running, (len(p_values) - rank) * p_values[index])
        adjusted[index] = min(1.0, running)
    return adjusted


def wilcoxon_detail(differences):
    """The signed-rank test with every choice the guide asks to be reported."""
    nonzero = differences[differences != 0]
    if nonzero.size == 0:
        return {"p": None, "method": "undefined (all differences zero)",
                "zeros": int(differences.size), "abs_ties": 0}
    magnitudes = np.abs(nonzero)
    abs_ties = int(magnitudes.size - np.unique(magnitudes).size)
    # scipy chooses exact only when no zeros were dropped and no |d| ties
    # remain; say which it used rather than leaving the reader to guess.
    exact = abs_ties == 0 and differences.size == nonzero.size and nonzero.size <= 50
    method = "exact" if exact else "asymptotic (normal approximation)"
    result = stats.wilcoxon(differences, zero_method="wilcox", alternative="two-sided")
    return {"p": float(result.pvalue), "method": method,
            "zeros": int(differences.size - nonzero.size), "abs_ties": abs_ties}


# The candidate feature stacks, contrasted against the selected one. A separate
# pre-specified family from the classifier comparison: three contrasts per
# season, adjusted within itself.
STACK_KEYS = ("after-gtb-b19", "after-gtb-b22", "after-gtb-b27")


def paired_contrasts(shards, season, districts, leader=LEADER,
                     comparators=None, family=None):
    """Leader minus each comparator, on the same district IDs, jointly resampled."""
    names = sorted(districts)
    rng = np.random.default_rng(BOOTSTRAP_SEED)
    draws = rng.integers(0, len(names), size=(BOOTSTRAP_REPLICATES, len(names)))

    keys = comparators or [f"after-{model}" for model in HEADLINE_MODELS]
    rows = []
    for key in keys:
        if key == leader:
            continue
        if any(key not in shards[f"{season}:{name}"]["matrices"] for name in names):
            continue
        differences = np.array([
            oa(shards[f"{season}:{name}"]["matrices"][leader])
            - oa(shards[f"{season}:{name}"]["matrices"][key])
            for name in names
        ])
        # One resample of district IDs, applied to both models at once, so the
        # interval is on the paired effect and not on two independent means.
        means = differences[draws].mean(axis=1)
        low, high = np.percentile(means, [2.5, 97.5])
        detail = wilcoxon_detail(differences)
        rows.append({
            "season": season,
            "contrast": f"{leader} - {key}",
            "districts": len(names),
            "mean_district_oa_difference_pp": float(differences.mean() * 100),
            "ci95_low_pp": float(low * 100),
            "ci95_high_pp": float(high * 100),
            "districts_leader_better": int((differences > 0).sum()),
            "districts_comparator_better": int((differences < 0).sum()),
            "districts_tied": detail["zeros"],
            "abs_difference_ties": detail["abs_ties"],
            "wilcoxon_p_raw": detail["p"],
            "wilcoxon_method": detail["method"],
            "wilcoxon_sided": "two-sided",
            "wilcoxon_zero_method": "wilcox (zeros dropped)",
            "family": family or f"{season}: classifier contrasts",
        })
    return rows


# ── writers ────────────────────────────────────────────────────────────────
def write_csv(name, fieldnames, rows):
    ARCHIVE.mkdir(parents=True, exist_ok=True)
    path = ARCHIVE / name
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
    print(f"wrote {path.relative_to(REPO)}  ({len(rows)} rows)")
    return path


def build_district_split(shards, splits, stratum_areas):
    role = {name: "test" for name in splits["test"]}
    role.update({name: "development" for name in splits["development"]})
    role.update({name: "training-withheld" for name in splits["training"]})
    centroids = json.loads((ASSETS / "mp_district_centroids.json").read_text())

    rows = []
    for name in sorted(role):
        centre = centroids.get(name, {})
        block = None
        if centre:
            block = f"{math.floor(centre['lat'])},{math.floor(centre['lon'])}"
        entry = {
            "district": name,
            "role": role[name],
            "block_id": block,
            "centroid_lon": centre.get("lon"),
            "centroid_lat": centre.get("lat"),
            "split_rule": "(floor(lat)+floor(lon)) mod 3 == 0 -> development",
            "split_seed": "none (deterministic)",
        }
        for season in SEASONS:
            shard = shards.get(f"{season}:{name}")
            key = f"{season}:{name}"
            areas = stratum_areas["strata"].get(key, {})
            entry[f"{season}_sample_n"] = shard["sample_count"] if shard else 0
            entry[f"{season}_district_area_km2"] = round(
                areas.get("district_area_m2", 0.0) / 1e6, 2)
            entry[f"{season}_consensus_area_km2"] = round(
                sum(areas.get("class_area_m2", {}).values()) / 1e6, 2)
        rows.append(entry)
    return rows


def build_metrics(shards, splits, provenance):
    rows = []
    # Only the "after" inventory is reported in this manuscript. The "before"
    # runs are the pre-revision five-class-with-Sand condition, kept in the
    # shards for provenance; they never learned Agriculture, so their column
    # marginal for that class is zero and the per-class identities are
    # undefined rather than wrong.
    model_keys = sorted({key for shard in shards.values() for key in shard["matrices"]
                         if key.startswith("after-")})
    for season in SEASONS:
        for group in ("development", "test"):
            districts = splits[group]
            for key in model_keys:
                matrix = pooled(shards, season, districts, key)
                if not np.asarray(matrix).sum():
                    continue
                metrics, n = verify(matrix, f"{season}/{group}/{key}")
                row = {
                    "run_id": f"v7-{season}-{group}-{key}",
                    "season": season,
                    "population": group,
                    "model_key": key,
                    "districts": len(districts),
                    "n": n,
                    "overall_accuracy": round(metrics["overall_accuracy"], 6),
                    "kappa": round(metrics["kappa"], 6),
                    "macro_f1": round(metrics["macro_f1"], 6),
                    "aggregation": "pooled counts over districts",
                    "uncertainty_method":
                        "percentile bootstrap, 5000 replicates, districts resampled",
                    "source_files": SHARD_GLOB,
                }
                for label in LABELS:
                    slug = label.lower().replace(" ", "_")
                    for stat in ("f1", "precision", "recall"):
                        value = metrics["per_class"][label][stat]
                        row[f"{slug}_{stat}"] = (
                            round(value, 6) if value is not None else "")
                rows.append(row)
    return rows


