def build_stratum_areas(shards, stratum_areas, splits):
    role = {name: "test" for name in splits["test"]}
    role.update({name: "development" for name in splits["development"]})
    role.update({name: "training-withheld" for name in splits["training"]})
    rows = []
    for key, record in sorted(stratum_areas["strata"].items()):
        season, district = record["season"], record["district"]
        shard = shards.get(f"{season}:{district}")
        for raw_label, area in sorted(record["class_area_m2"].items()):
            label = canonical_label(raw_label)
            index = LABELS.index(label)
            sample_n = 0
            if shard:
                sample_n = int(sum(shard["matrices"][LEADER][index]))
            rows.append({
                "season": season,
                "district": district,
                "role": role.get(district, "unassigned"),
                "consensus_class": label,
                "eligible_area_km2": round((area or 0.0) / 1e6, 4),
                "sample_n": sample_n,
                "sampled": "yes" if sample_n else "no",
                "exclusion_reason": "" if sample_n else
                    "no consensus pixel of this class cleared the 20-point quota",
                "weight_scale_m": stratum_areas.get("scale_m"),
            })
    return rows


def build_feature_experiments(shards, splits):
    """The development-side feature experiments, recomputed from their matrices.

    These live in their own archives because they were run before the frozen
    pipeline existed, and that is exactly why they need to be folded in here:
    the manuscript quotes a 27-band baseline from this sweep next to a 27-band
    figure from the frozen run, and the two differ. Emitting both with their
    source file named makes the offset visible instead of leaving a reader to
    discover that two numbers for "the same stack" disagree.
    """
    rows = []
    ablation = load_json(BAND_ABLATION)
    for season, scores in ablation["scores"].items():
        for key, value in scores.items():
            rows.append({
                "experiment": "cumulative feature families and leave-one-band-out",
                "source_file": BAND_ABLATION,
                "season": season,
                "population": "development (15 districts)",
                "tuning": "pre-hyperparameter-search settings",
                "variant": key,
                "n": value.get("sample_count"),
                "overall_accuracy": round(value["overall_accuracy"], 6),
                "open_land_recall":
                    round(value["per_class_recall"]["Open Land"], 6),
                "built_area_precision":
                    round(value["per_class_precision"]["Built Area"], 6),
            })

    family = load_json(FAMILY_ABLATION)
    for season in SEASONS:
        keys = sorted({k for shard in family["shards"].values()
                       for k in shard["matrices"]})
        for key in keys:
            total = np.zeros((len(LABELS), len(LABELS)), dtype=int)
            for shard in family["shards"].values():
                if shard["season"] == season and key in shard["matrices"]:
                    total += np.asarray(shard["matrices"][key], dtype=int)
            if not total.sum():
                continue
            metrics, n = verify(total.tolist(), f"family/{season}/{key}")
            rows.append({
                "experiment": "leave-one-family-out",
                "source_file": FAMILY_ABLATION,
                "season": season,
                "population": "development (15 districts)",
                "tuning": "pre-hyperparameter-search settings",
                "variant": key,
                "n": n,
                "overall_accuracy": round(metrics["overall_accuracy"], 6),
                "open_land_recall":
                    round(metrics["per_class"]["Open Land"]["recall"], 6),
                "built_area_precision":
                    round(metrics["per_class"]["Built Area"]["precision"], 6),
            })

    # And the same stacks under the frozen pipeline, from the primary record.
    for season in SEASONS:
        for group in ("development", "test"):
            for key in ("after-gtb", "after-gtb-b19", "after-gtb-b22",
                        "after-gtb-b27"):
                matrix = pooled(shards, season, splits[group], key)
                if not np.asarray(matrix).sum():
                    continue
                metrics, n = verify(matrix, f"stack/{season}/{group}/{key}")
                rows.append({
                    "experiment": "candidate feature stacks, frozen pipeline",
                    "source_file": PREDICTIONS,
                    "season": season,
                    "population": f"{group} ({len(splits[group])} districts)",
                    "tuning": "frozen winter hyperparameter selection",
                    "variant": key,
                    "n": n,
                    "overall_accuracy": round(metrics["overall_accuracy"], 6),
                    "open_land_recall":
                        round(metrics["per_class"]["Open Land"]["recall"], 6),
                    "built_area_precision":
                        round(metrics["per_class"]["Built Area"]["precision"], 6),
                })
    return rows


def build_spatial_transfer(splits):
    """Per-district distance and accuracy, and the regression on both populations.

    The manuscript's distance analysis pools all 44 evaluation districts, which
    mixes the population choices were made on with the population they are
    reported on. That makes it exploratory, and the honest way to say so is to
    publish the test-only fit beside it rather than to describe the pooled one
    as if it were held out.
    """
    payload = load_json(SPATIAL_UNCERTAINTY)
    rows = []
    for season in SEASONS:
        transfer = payload["seasons"][season].get("transfer")
        if not transfer:
            continue
        test = set(splits["test"])
        for record in transfer["districts"]:
            rows.append({
                "season": season,
                "district": record["district"],
                "role": "test" if record["district"] in test else "development",
                "distance_km_from_jabalpur": round(record["distance_km"], 3),
                "overall_accuracy": round(record["overall_accuracy"], 6),
                "sample_n": record["sample_count"],
            })

        for population, names in (("all 44 evaluation districts", None),
                                  ("29 test districts only", test)):
            subset = [r for r in transfer["districts"]
                      if names is None or r["district"] in names]
            x = np.array([r["distance_km"] for r in subset]) / 100.0
            y = np.array([r["overall_accuracy"] for r in subset])
            fit = stats.linregress(x, y)
            half = 1.959964 * fit.stderr
            rows.append({
                "season": season,
                "district": f"[fit: {population}]",
                "role": "regression summary",
                "distance_km_from_jabalpur": len(subset),
                "overall_accuracy": round(float(fit.slope) * 100, 4),
                "sample_n": (f"slope pp/100km with 95% CI "
                             f"[{(fit.slope - half) * 100:+.2f}, "
                             f"{(fit.slope + half) * 100:+.2f}], "
                             f"R2={fit.rvalue ** 2:.4f}, p={fit.pvalue:.4f}"),
            })
    return rows


def build_reproduction_check(shards, splits):
    """Stored evaluation against an independent re-run, district by district.

    Returns nothing until scripts/export_predictions_table.py has been run.
    The comparison is deliberately one-directional: the stored run is what the
    manuscript reports, and this says how closely it can be reproduced, not
    which of the two is right.
    """
    predictions = ASSETS / PREDICTIONS
    if not predictions.exists():
        return []
    rerun, _ = shards_from_predictions(predictions)
    role = {name: "test" for name in splits["test"]}
    role.update({name: "development" for name in splits["development"]})
    role.update({name: "training-withheld" for name in splits["training"]})

    rows = []
    for key in sorted(rerun):
        season, district = key.split(":", 1)
        stored = shards.get(key, {}).get("matrices", {})
        for model, matrix in sorted(rerun[key]["matrices"].items()):
            if model not in stored:
                continue
            new = np.asarray(matrix, dtype=int)
            old = np.asarray(stored[model], dtype=int)
            if new.sum() != old.sum():
                moved = None
            else:
                # Half the L1 distance between two confusion matrices of equal
                # total. This is NOT a count of predictions that changed: two
                # points of the same reference class swapping predicted labels
                # leave the matrix untouched and score 0. Under matched samples
                # and matched reference labels it is a lower bound on that
                # count. The exact figure needs a join on sample_id against the
                # stored run's per-point predictions, which were never kept.
                moved = int(np.abs(new - old).sum() // 2)
            rows.append({
                "season": season,
                "district": district,
                "role": role.get(district, "unassigned"),
                "model_key": model,
                "stored_n": int(old.sum()),
                "rerun_n": int(new.sum()),
                "stored_overall_accuracy": round(oa(old.tolist()), 6),
                "rerun_overall_accuracy": round(oa(new.tolist()), 6),
                # Named for what Eq. (matrix redistribution) computes. The old
                # name "points_moved" claimed more than the quantity supports.
                "matrix_redistribution": moved,
                "identical": bool(moved == 0),
            })
    return rows


